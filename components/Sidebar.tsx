export function Sidebar({ userRole }: { userRole?: string }) {
  const pathname = usePathname();

  // Helper to determine if a route is active
  const isItemActive = (href: string) => {
    if (href === "/dashboard") return pathname === "/dashboard";
    if (href === "/invoices") return pathname.startsWith("/invoices") || pathname.startsWith("/proforma-invoices");
    if (href === "/finance") return pathname.startsWith("/finance") || pathname.startsWith("/revenue") || pathname.startsWith("/ledger");
    if (href === "/expenses") return pathname.startsWith("/expenses") || pathname.startsWith("/expense-categories");
    return pathname.startsWith(href);
  };

  const filteredNavItems = navItems.filter((item) => {
    if (item.name === "Settings" && userRole !== "ADMIN") return false;
    if (item.name === "Dashboard" && userRole !== "ADMIN") return false;
    return true;
  });

  if (userRole !== "ADMIN") {
    // Add Home at the top for regular users
    filteredNavItems.unshift({
      name: "Home",
      href: "/home",
      icon: (
        <svg className="w-5 h-5 mr-3" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M3 12l2-2m0 0l7-7 7 7M5 10v10a1 1 0 001 1h3m10-11l2 2m-2-2v10a1 1 0 01-1 1h-3m-6 0a1 1 0 001-1v-4a1 1 0 011-1h2a1 1 0 011 1v4a1 1 0 001 1m-6 0h6" />
        </svg>
      )
    });
  }

  if (userRole === "ADMIN") {
    filteredNavItems.splice(filteredNavItems.length - 1, 0, {
      name: "Users",
      href: "/users",
      icon: (
        <svg className="w-5 h-5 mr-3" fill="none" stroke="currentColor" viewBox="0 0 24 24">
          <path strokeLinecap="round" strokeLinejoin="round" strokeWidth="2" d="M12 4.354a4 4 0 110 5.292M15 21H3v-1a6 6 0 0112 0v1zm0 0h6v-1a6 6 0 00-9-5.197M13 7a4 4 0 11-8 0 4 4 0 018 0z" />
        </svg>
      )
    });
  }

  return (
    <aside className="w-64 bg-theme-bg text-white min-h-screen p-4 flex flex-col">
      <div className="text-xl font-bold mb-8 px-2 text-white">Billing ERP</div>
      <nav className="flex-1 overflow-y-auto">
        <ul className="space-y-1">
          {filteredNavItems.map((item) => {
            const active = isItemActive(item.href);
            return (
              <li key={item.name}>
                <Link
                  href={item.href}
                  className={`flex items-center px-3 py-2.5 rounded-md text-sm font-medium transition-colors ${
                    active
                      ? "bg-gray-800 text-white"
                      : "text-gray-300 hover:bg-gray-800 hover:text-white"
                  }`}
                >
                  <span className={active ? "text-blue-400" : "text-theme-text-muted"}>
                    {item.icon}
                  </span>
                  {item.name}
                </Link>
              </li>
            );
          })}
        </ul>
      </nav>
    </aside>
  );
}
